import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { discover } from '../src/core/discover.js';
import { cachedFetcher, checkURL } from '../src/core/io.js';
const url = 'https://raw.githubusercontent.com/markdown-it/markdown-it/master/README.md';
const cacheDir = path.resolve('output/remote-cache');
const fetcher = cachedFetcher(cacheDir);
const live = await fetcher(url, 5 * 1024 * 1024, true);
assert(live.data.toString().includes('markdown-it'));
const cached = await fetcher(url, 5 * 1024 * 1024, false);
assert.deepEqual(cached.data, live.data);
await assert.rejects(checkURL('http://127.0.0.1/secret.md'), /Private/);
await assert.rejects(checkURL('http://[::1]/secret.md'), /Private/);
await assert.rejects(checkURL('https://user:password@example.com/a.md'), /credentials/);
const plan = await discover(url, { cacheDir, maxDepth: 0, maxDocuments: 1 });
assert(plan.documents[0].available);
assert.equal(plan.documents[0].content, live.data.toString());
await fs.writeFile('output/remote-reading-plan.json', JSON.stringify(plan, null, 2));
console.log(`Public remote fetch and cache readback passed: ${live.data.length} bytes, ${plan.documents[0].links.length} links. Private URLs rejected.`);
