import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import { serve } from '../src/server.js';
import { launchBrowser } from '../src/core/export.js';
import { validatePlan } from '../src/core/model.js';
const plan = validatePlan(JSON.parse(await fs.readFile('output/acceptance/reading-plan.json', 'utf8')));
const { server, url } = await serve({ port: 4318, plan, production: true });
const { browser, close } = await launchBrowser();
const failures: string[] = [];
try {
  const page = await browser.newPage(); await page.setViewport({ width: 1440, height: 1000 });
  page.on('pageerror', e => failures.push(String(e)));
  const forbidden = await fetch('http://127.0.0.1:4318/api/plan'); assert.equal(forbidden.status, 403);
  await page.goto(url, { waitUntil: 'networkidle0' });
  await page.waitForSelector('.packet-node');
  assert.equal(await page.$$eval('.packet-node', nodes => nodes.length), 6);
  const count = () => page.$eval('.pill', el => el.textContent);
  assert.equal(await count(), '5 selected');
  await page.click('button[aria-label="Include A disconnected thought"]');
  await page.waitForFunction(() => document.querySelector('.pill')?.textContent === '6 selected');
  assert.equal(await count(), '6 selected');
  await page.click('button[aria-label="Exclude A disconnected thought"]');
  await page.waitForFunction(() => document.querySelector('.pill')?.textContent === '5 selected');
  assert.equal(await count(), '5 selected');
  await page.type('input[aria-label="New section name"]', 'Background');
  await page.click('.add-section button');
  const newSection = await page.$eval('input[aria-label="Section title"]', el => (el as HTMLInputElement).value); assert.equal(newSection, 'Background');
  await page.select('select[aria-label="Parent of Research notes"]', await page.$eval('select[aria-label="Parent of Research notes"]', el => [...(el as HTMLSelectElement).options].find(o => o.textContent === 'Background')!.value));
  const saved = await page.evaluate(async () => {
    const original = URL.createObjectURL; let captured: Blob | undefined;
    URL.createObjectURL = value => { captured = value as Blob; return original(value); };
    (document.querySelector('header button.secondary') as HTMLButtonElement).click();
    URL.createObjectURL = original;
    if (!captured) throw new Error('Save plan did not create a snapshot');
    return captured.text();
  });
  const edited = validatePlan(JSON.parse(saved)); assert(edited.tree.some(n => n.title === 'Background'));
  await fs.writeFile('output/acceptance/edited-plan.json', saved);
  await (await page.$('input[type=file]'))!.uploadFile('output/acceptance/edited-plan.json');
  await page.waitForFunction(() => document.querySelector('.status') === null);
  assert.equal(await count(), '5 selected');
  await page.screenshot({ path: 'output/acceptance/editor.png', fullPage: true });
  await page.click('.workspace-bar nav button:nth-child(2)');
  await page.waitForSelector('iframe', { timeout: 15000 });
  const frame = await (await page.$('iframe'))!.contentFrame(); assert(frame);
  await frame.waitForFunction('window.packetReady === true', { timeout: 30000 });
  assert.equal(await frame.$$eval('.mermaid svg', nodes => nodes.length), 1);
  assert((await frame.$eval('body', el => el.textContent))?.includes('한국어'));
  assert((await frame.$eval('body', el => el.textContent))?.includes('Background'));
  await page.screenshot({ path: 'output/acceptance/preview.png', fullPage: true });
  await page.select('select[aria-label="PDF mode"]', 'documents');
  await page.waitForFunction(() => document.querySelector('.preview-container iframe') !== null);
  await page.setViewport({ width: 600, height: 900 }); await page.screenshot({ path: 'output/acceptance/mobile.png', fullPage: true });
  assert.deepEqual(failures, []);
  // Exercise the exact HTTP export used by the editor with its captured token.
  const token = new URL(url).searchParams.get('token')!;
  assert.equal((await fetch('http://127.0.0.1:4318/api/plan', { headers: { 'x-packet-token': token, origin: 'https://untrusted.example' } })).status, 403);
  assert.equal((await fetch('http://127.0.0.1:4318/api/preview', { method: 'POST', headers: { 'content-type': 'application/json', 'x-packet-token': token }, body: '{"version":2}' })).status, 400);
  const response = await fetch('http://127.0.0.1:4318/api/export', { method: 'POST', headers: { 'content-type': 'application/json', 'x-packet-token': token }, body: JSON.stringify(plan) });
  assert.equal(response.status, 200); assert.equal(response.headers.get('content-type'), 'application/pdf');
  assert(Buffer.from(await response.arrayBuffer()).subarray(0, 4).toString() === '%PDF');
  console.log('UI acceptance passed: graph selection, sections, reparenting, plan save/load, Mermaid/math preview, responsive layout, API access checks, HTTP export; no browser errors.');
} finally { await close(); await new Promise<void>((resolve, reject) => server.close(e => e ? reject(e) : resolve())); }
